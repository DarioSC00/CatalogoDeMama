-- Storage para las imágenes del catálogo.
-- Ejecuta este bloque con el SQL Editor de Supabase; la clave anon no puede crear buckets.
INSERT INTO storage.buckets (id, name, public)
VALUES ('fotos-catalogo', 'fotos-catalogo', TRUE)
ON CONFLICT (id) DO UPDATE SET public = TRUE;

DROP POLICY IF EXISTS "fotos_catalogo_public_read" ON storage.objects;
CREATE POLICY "fotos_catalogo_public_read" ON storage.objects
FOR SELECT USING (bucket_id = 'fotos-catalogo');

DROP POLICY IF EXISTS "fotos_catalogo_authenticated_insert" ON storage.objects;
CREATE POLICY "fotos_catalogo_authenticated_insert" ON storage.objects
FOR INSERT TO authenticated
WITH CHECK (bucket_id = 'fotos-catalogo');

DROP POLICY IF EXISTS "fotos_catalogo_authenticated_update" ON storage.objects;
CREATE POLICY "fotos_catalogo_authenticated_update" ON storage.objects
FOR UPDATE TO authenticated
USING (bucket_id = 'fotos-catalogo')
WITH CHECK (bucket_id = 'fotos-catalogo');

DROP POLICY IF EXISTS "fotos_catalogo_authenticated_delete" ON storage.objects;
CREATE POLICY "fotos_catalogo_authenticated_delete" ON storage.objects
FOR DELETE TO authenticated
USING (bucket_id = 'fotos-catalogo');

