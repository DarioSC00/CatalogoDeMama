CREATE TABLE IF NOT EXISTS categorias (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL UNIQUE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS productos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL,
  descripcion TEXT,
  precio NUMERIC(12,2) NOT NULL DEFAULT 0,
  categoria TEXT,
  categoria_id BIGINT REFERENCES categorias(id),
  url_imagen TEXT,
  disponible BOOLEAN DEFAULT TRUE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Migración para instalaciones creadas con una versión anterior del esquema.
-- CREATE TABLE IF NOT EXISTS no agrega columnas a tablas ya existentes.
ALTER TABLE productos ADD COLUMN IF NOT EXISTS categoria TEXT;
ALTER TABLE productos ADD COLUMN IF NOT EXISTS stock INTEGER NOT NULL DEFAULT 0;

CREATE INDEX IF NOT EXISTS idx_productos_categoria ON productos(categoria);
CREATE INDEX IF NOT EXISTS idx_productos_disponible ON productos(disponible);
CREATE INDEX IF NOT EXISTS idx_productos_stock ON productos(stock);

-- Modelo del Dashboard: registra cada entrada o salida de inventario.
CREATE TABLE IF NOT EXISTS dashboard (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  producto_id BIGINT NOT NULL REFERENCES productos(id) ON DELETE CASCADE,
  tipo_movimiento TEXT NOT NULL CHECK (tipo_movimiento IN ('entrada', 'salida')),
  cantidad INTEGER NOT NULL CHECK (cantidad > 0),
  fecha_movimiento TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  notas TEXT,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_dashboard_producto ON dashboard(producto_id);
CREATE INDEX IF NOT EXISTS idx_dashboard_tipo ON dashboard(tipo_movimiento);
CREATE INDEX IF NOT EXISTS idx_dashboard_fecha ON dashboard(fecha_movimiento DESC);

-- Resumen que usa el Dashboard para ordenar los productos por entradas.
DROP VIEW IF EXISTS dashboard_productos;
CREATE OR REPLACE VIEW dashboard_productos AS
SELECT
  p.id,
  p.nombre,
  p.categoria,
  p.precio,
  p.url_imagen,
  p.disponible,
  COALESCE(SUM(d.cantidad) FILTER (WHERE d.tipo_movimiento = 'entrada'), 0) AS total_ingresos,
  COALESCE(SUM(d.cantidad) FILTER (WHERE d.tipo_movimiento = 'salida'), 0) AS total_salidas,
  MAX(d.fecha_movimiento) FILTER (WHERE d.tipo_movimiento = 'entrada') AS ultimo_ingreso,
  p.created_at
FROM productos p
LEFT JOIN dashboard d ON d.producto_id = p.id
GROUP BY p.id, p.nombre, p.categoria, p.precio, p.url_imagen, p.disponible, p.created_at
ORDER BY total_ingresos DESC, p.created_at DESC;

